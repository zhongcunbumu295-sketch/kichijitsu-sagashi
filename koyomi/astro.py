def _series(tables, tau: float) -> float:
    total = 0.0
    for power, table in enumerate(tables):
        total += sum(a * math.cos(b + c * tau) for a, b, c in table) * tau ** power
    return total / 1e8


# ---------------------------------------------------------------- 時刻の変換
def jd_from_datetime(dt: datetime) -> float:
    """タイムゾーン付き datetime → ユリウス日（UT）。"""
    dt = dt.astimezone(timezone.utc)
    days = (dt - datetime(2000, 1, 1, 12, tzinfo=timezone.utc)).total_seconds() / 86400
    return J2000 + days


def datetime_from_jd(jd: float) -> datetime:
    """ユリウス日（UT）→ 日本時間の datetime。"""
    base = datetime(2000, 1, 1, 12, tzinfo=timezone.utc)
    return (base + timedelta(days=jd - J2000)).astimezone(JST)


def jde_to_jst(jde: float) -> datetime:
    """力学時のユリウス日 → 日本時間。"""
    return datetime_from_jd(jde - DELTA_T_SECONDS / 86400)


def jst_to_jde(dt: datetime) -> float:
    return jd_from_datetime(dt) + DELTA_T_SECONDS / 86400


# ---------------------------------------------------------------- 太陽
def sun_apparent_longitude(jde: float) -> float:
    """太陽の視黄経（度, 0〜360）。"""
    tau = (jde - J2000) / 365250
    t = tau * 10
    lon = math.degrees(_series([_L0, _L1, _L2, _L3, _L4, _L5], tau))
    radius = _series([_R0, _R1, _R2, _R3, _R4], tau)
    theta = lon + 180.0
    # FK5 への補正
    theta += -0.09033 / 3600
    # 章動（黄経）
    omega = math.radians(125.04452 - 1934.136261 * t)
    l_sun = math.radians(280.4665 + 36000.7698 * t)
    l_moon = math.radians(218.3165 + 481267.8813 * t)
    dpsi = (-17.20 * math.sin(omega) - 1.32 * math.sin(2 * l_sun)
            - 0.23 * math.sin(2 * l_moon) + 0.21 * math.sin(2 * omega))
    theta += dpsi / 3600
    # 光行差
    theta += -20.4898 / (3600 * radius)
    return theta % 360


def solar_term_jde(target_deg: float, jde_guess: float) -> float:
    """太陽の視黄経が target_deg になる時刻（力学時のユリウス日）。"""
    jde = jde_guess
    for _ in range(30):
        diff = (target_deg - sun_apparent_longitude(jde) + 180) % 360 - 180
        jde += diff * 365.2422 / 360
        if abs(diff) < 1e-9:
            break
    return jde


def solar_longitude_events(start: date, end: date, step_deg: int = 15):
    """start〜end（日本時間の日付）に太陽黄経が step_deg の倍数になる瞬間を列挙する。

    戻り値: [(黄経, 日本時間 datetime), ...]
    """
    jde = jst_to_jde(datetime(start.year, start.month, start.day, tzinfo=JST))
    jde_end = jst_to_jde(datetime(end.year, end.month, end.day, tzinfo=JST) + timedelta(days=1))
    events = []
    lon = sun_apparent_longitude(jde)
    target = (math.floor(lon / step_deg) + 1) * step_deg % 360
    while True:
        guess = jde + ((target - lon) % 360) * 365.2422 / 360
        jde = solar_term_jde(target, guess)
        if jde >= jde_end:
            break
        events.append((target, jde_to_jst(jde)))
        lon = target
        target = (target + step_deg) % 360
    return events


# ---------------------------------------------------------------- 月（朔望）
def moon_phase_jde(k: float) -> float:
    """朔（k が整数）または望（k が整数 + 0.5）の時刻（力学時のユリウス日）。"""
    t = k / 1236.85
    jde = (2451550.09766 + 29.530588861 * k + 0.00015437 * t ** 2
           - 0.000000150 * t ** 3 + 0.00000000073 * t ** 4)
    e = 1 - 0.002516 * t - 0.0000074 * t ** 2
    m = math.radians(2.5534 + 29.10535670 * k - 0.0000014 * t ** 2 - 0.00000011 * t ** 3)
    mp = math.radians(201.5643 + 385.81693528 * k + 0.0107582 * t ** 2
                      + 0.00001238 * t ** 3 - 0.000000058 * t ** 4)
    f = math.radians(160.7108 + 390.67050284 * k - 0.0016118 * t ** 2
                     - 0.00000227 * t ** 3 + 0.000000011 * t ** 4)
    om = math.radians(124.7746 - 1.56375588 * k + 0.0020672 * t ** 2 + 0.00000215 * t ** 3)
    sin = math.sin
    is_full = abs(k - math.floor(k) - 0.5) < 1e-6
    if is_full:
        c = (-0.40614 * sin(mp) + 0.17302 * e * sin(m) + 0.01614 * sin(2 * mp)
             + 0.01043 * sin(2 * f) + 0.00734 * e * sin(mp - m) - 0.00515 * e * sin(mp + m)
             + 0.00209 * e * e * sin(2 * m))
    else:
        c = (-0.40720 * sin(mp) + 0.17241 * e * sin(m) + 0.01608 * sin(2 * mp)
             + 0.01039 * sin(2 * f) + 0.00739 * e * sin(mp - m) - 0.00514 * e * sin(mp + m)
             + 0.00208 * e * e * sin(2 * m))
    c += (-0.00111 * sin(mp - 2 * f) - 0.00057 * sin(mp + 2 * f)
          + 0.00056 * e * sin(2 * mp + m) - 0.00042 * sin(3 * mp)
          + 0.00042 * e * sin(m + 2 * f) + 0.00038 * e * sin(m - 2 * f)
          - 0.00024 * e * sin(2 * mp - m) - 0.00017 * sin(om)
          - 0.00007 * sin(mp + 2 * m) + 0.00004 * sin(2 * mp - 2 * f)
          + 0.00004 * sin(3 * m) + 0.00003 * sin(mp + m - 2 * f)
          + 0.00003 * sin(2 * mp + 2 * f) - 0.00003 * sin(mp + m + 2 * f)
          + 0.00003 * sin(mp - m + 2 * f) - 0.00002 * sin(mp - m - 2 * f)
          - 0.00002 * sin(3 * mp + m) + 0.00002 * sin(4 * mp))
    planetary = [
        (0.000325, 299.77 + 0.107408 * k - 0.009173 * t ** 2),
        (0.000165, 251.88 + 0.016321 * k), (0.000164, 251.83 + 26.651886 * k),
        (0.000126, 349.42 + 36.412478 * k), (0.000110, 84.66 + 18.206239 * k),
        (0.000062, 141.74 + 53.303771 * k), (0.000060, 207.14 + 2.453732 * k),
        (0.000056, 154.84 + 7.306860 * k), (0.000047, 34.52 + 27.261239 * k),
        (0.000042, 207.19 + 0.121824 * k), (0.000040, 291.34 + 1.844379 * k),
        (0.000037, 161.72 + 24.198154 * k), (0.000035, 239.56 + 25.513099 * k),
        (0.000023, 331.55 + 3.592518 * k),
    ]
    c += sum(coef * sin(math.radians(arg)) for coef, arg in planetary)
    return jde + c


def moon_phases(start: date, end: date, full: bool = False) -> list[datetime]:
    """start〜end（日本時間の日付）の朔（full=True なら望）の日本時間を列挙する。"""
    k = math.floor((start.year + (start.timetuple().tm_yday - 1) / 365.25 - 2000) * 12.3685) - 2
    offset = 0.5 if full else 0.0
    result = []
    while True:
        dt = jde_to_jst(moon_phase_jde(k + offset))
        if dt.date() > end:
            break
        if dt.date() >= start:
            result.append(dt)
        k += 1
    return result
